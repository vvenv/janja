import { expect, it } from 'vitest';
import { analyzeTemplate, generateDeclarations } from './analyze';

it('finds the data a template reads', async () => {
  const analysis = await analyzeTemplate(`
    {{= title | upper }}{{= user.name }}
    {{ if show and not hidden }}{{= a if b else c }}{{ elif other }}{{ endif }}
    {{ for item of items | sort }}{{= item.id }}{{= loop.index }}{{= outer }}{{ else }}{{= empty }}{{ endfor }}
    {{ for (x, y=dy) of pairs }}{{= x }}{{= y }}{{ endfor }}
    {{= fn(arg, 1) | truncate(len, mode=m) }}
  `);

  expect(analysis.variables).toEqual([
    'a',
    'arg',
    'b',
    'c',
    'dy',
    'empty',
    'fn',
    'hidden',
    'items',
    'len',
    'm',
    'other',
    'outer',
    'pairs',
    'show',
    'title',
    'user',
  ]);
  expect(analysis.filters).toEqual(['sort', 'truncate', 'upper']);
});

it('knows what the template defines itself', async () => {
  const analysis = await analyzeTemplate(`
    {{= early }}{{ set early = 1 }}{{= early }}
    {{ set (p, q) = source }}{{= p }}{{= q }}
    {{ capture cap }}{{= inside }}{{ endcapture }}{{= cap }}
    {{ macro m(x, y=def) }}{{= x }}{{= y }}{{= free }}{{ caller }}{{ endmacro }}
    {{ call m(val) }}{{= body }}{{ endcall }}
    {{ with ctx }}{{= prop | lower }}{{ endwith }}
    {{ block content }}{{= page }}{{ endblock }}
    {{ for i of list }}{{ set tmp = i }}{{ endfor }}{{= tmp }}{{= i }}
  `);

  expect(analysis.variables).toEqual([
    'body',
    'ctx',
    'def',
    'early',
    'free',
    'i',
    'inside',
    'list',
    'page',
    'source',
    'tmp',
    'val',
  ]);
  expect(analysis.macros).toEqual(['m']);
  expect(analysis.blocks).toEqual(['content']);
  expect(analysis.filters).toEqual(['lower']);
});

it('follows includes through the loader', async () => {
  const files: Record<string, string> = {
    header: '{{= site }}{{ include "nav" }}',
    nav: '{{ for link of links }}{{= link }}{{ endfor }}{{ include "header" }}',
  };

  const analysis = await analyzeTemplate(
    '{{ set local = 1 }}{{ include "header" }}{{ include "missing" }}{{= page }}',
    {
      loader: async (path) => {
        if (!(path in files)) {
          throw new Error('not found');
        }

        return files[path];
      },
    },
  );

  expect(analysis.includes).toEqual(['header', 'missing', 'nav']);
  expect(analysis.variables).toEqual(['links', 'page', 'site']);
});

it('generates declarations for precompiled modules', () => {
  expect(generateDeclarations({ variables: ['items', 'title'] }))
    .toMatchInlineSnapshot(`
      "// Generated by the Janja precompiler. Do not edit.
      import type { Script } from 'janja';

      /** The data this template reads. */
      export interface TemplateData {
        items?: unknown;
        title?: unknown;
      }

      export declare const script: Script;

      export default script;
      "
    `);
  expect(
    generateDeclarations({ variables: [] }, { includeRuntime: true }),
  ).toContain('export default function render(\n  data?: TemplateData,');
});
