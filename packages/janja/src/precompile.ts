import { analyzeTemplate, generateDeclarations } from './analyze';
import { Compiler } from './compiler';
import * as filters from './filters';
import { compilerOptions, mergeOptions } from './options';
import { CONTEXT, ESCAPE, FILTERS, WRITE } from './param-names';
import { plugins } from './plugins';
import { generateSourceMap, type SourceMapV3 } from './source-map-v3';
import type { CompilerOptions } from './types';

export interface PrecompileOptions extends CompilerOptions {
  /**
   * Also export a ready-to-call `render(globals, options)` function. The
   * generated module then imports the runtime from `janja`.
   */
  includeRuntime?: boolean;
  /** Also return a source map (`precompile` only) */
  sourceMap?: boolean;
  /** Name of the template, recorded in the source map */
  filename?: string;
  /** Also return TypeScript declarations for the module (`precompile` only) */
  dts?: boolean;
}

const banner = '// Generated by the Janja precompiler. Do not edit.';

export interface PrecompileResult {
  /** Source of an ES module exporting the compiled template as `script` */
  code: string;
  /** Present when the `sourceMap` option is set */
  map?: SourceMapV3;
  /** Present when the `dts` option is set */
  dts?: string;
}

/**
 * Compile a template into the source of an ES module, optionally with a
 * source map pointing back into the template.
 *
 * The module's `script` export is the compiled template; pass it to
 * `renderCompiled` to render it without compiling anything at runtime.
 */
export async function precompile(
  template: string,
  {
    includeRuntime,
    sourceMap,
    filename,
    dts,
    ...options
  }: PrecompileOptions = {},
): Promise<PrecompileResult> {
  const compiler = new Compiler(
    mergeOptions(compilerOptions, { filters, plugins }, options),
  );

  await compiler.compile(template);

  const head = `${banner}${
    includeRuntime ? "\nimport { renderCompiled } from 'janja';\n" : ''
  }
export function script(${CONTEXT}, ${ESCAPE}, ${FILTERS}, ${WRITE}) {
`;

  const tail = includeRuntime
    ? `
}

export default function render(globals = {}, options) {
  return renderCompiled(script, globals, options);
}
`
    : `
}

export default script;
`;

  return {
    code: `${head}${compiler.code}${tail}`,
    map: sourceMap
      ? generateSourceMap(compiler.mappings, {
          source: filename ?? 'template.janja',
          sourceContent: template,
          // The compiled code is the line right after the head
          line: head.split('\n').length - 1,
        })
      : undefined,
    dts: dts
      ? generateDeclarations(await analyzeTemplate(template, options), {
          includeRuntime,
        })
      : undefined,
  };
}

/**
 * Compile a template into the source of an ES module. See `precompile`.
 */
export async function precompileTemplate(
  template: string,
  options: PrecompileOptions = {},
): Promise<string> {
  return (await precompile(template, options)).code;
}
